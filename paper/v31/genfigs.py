    alpha = X ** (-1.0 / p)
    t = R.t
    kstar, k_ak, k_ad, k_proj, k_dec, k_M = kappa_vals(p, t)

    # Exact 1-step relative errors and correct digits for all 6 supports
    s_mb = 1.0 - (X - 1.0) / (X * sum(s**j for j in range(p)))
    s_ak = s * k_ak / (k_ak - 1.0 + t)
    s_ad = s * k_ad / (k_ad - 1.0 + t)
