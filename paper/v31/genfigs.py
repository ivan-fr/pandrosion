def c(pt):
    return f"({pt[0]:.4f},{pt[1]:.4f})"


def meet(p1, d1, p2, d2):
    """Intersection of p1 + a d1 and p2 + b d2."""
    det = d1[0] * (-d2[1]) - d1[1] * (-d2[0])
    rx, ry = p2[0] - p1[0], p2[1] - p1[1]
    a = (rx * (-d2[1]) - ry * (-d2[0])) / det
    return (p1[0] + a * d1[0], p1[1] + a * d1[1])


def mean_consts(p):
    m = (p - 2) * (47 * p**2 + 21 * p + 4) / (60 * p * (4 * p**2 - 1))
    g = 16 * (p + 1) * (4 * p**2 - 1) / (15 * p * (5 * p**2 + 4))
    n = 49 * p * (p + 1) * (p**2 - 4) / (10 * (4 * p**2 - 1) * (5 * p**2 + 4))
    d = (5 * p**2 + 4) / (84 * p**2)
    return m, g, n, d


def kappa_vals(p, t):
    """Exact and approximate support slopes kappa(t) for degree p."""
    kstar = p if abs(t - 1.0) < 1e-14 else (t - 1.0) / (t ** (1.0 / p) - 1.0)
    k_ak = float(p)
    k_ad = 0.5 * (p + 1.0 + (p - 1.0) * t)
    k_proj = 2.0 * p * ((2.0 * p - 1.0) * t + p + 1.0) / ((p + 1.0) * t + 5.0 * p - 1.0)
    q5 = sqrt(((p - 2.0) * (t * t + 1.0) + (10.0 * p + 4.0) * t) / (12.0 * p))
    k_dec = 1.0 + (p - 1.0) * q5
    m, g, n, d = mean_consts(p)
    qM = m * (1.0 + t) + g * sqrt(t) - n * sqrt(t + d * (t - 1.0) ** 2)
    k_M = 1.0 + (p - 1.0) * qM
    return kstar, k_ak, k_ad, k_proj, k_dec, k_M


