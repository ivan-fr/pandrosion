def fig_projective():
    R = cubic_rect()
    p, X, W, H, t = R.p, R.X, R.W, R.H, R.t
    ly = H * (1 + (5 * p - 1) / ((p + 1) * X))
    Z = (W * (1 + (5 * p - 1) / (2 * p * (2 * p - 1))), H * (1 + (p + 1) / ((2 * p - 1) * X)))
    D = meet(Z, (R.E[0] - Z[0], R.E[1] - Z[1]), (0, ly), (1, 0))
    T, Pp = R.step(R.A, (D[0] - W, D[1] - H))
    kap = 2 * p * ((2 * p - 1) * t + p + 1) / ((p + 1) * t + 5 * p - 1)
    assert abs((D[1] - H) / (D[0] - W) * W * X / H - kap) < 1e-12
    assert abs((1 - Pp[1] / H) - R.s * kap / (kap - 1 + t)) < 1e-12
