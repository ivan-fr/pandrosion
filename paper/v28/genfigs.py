def fig_arc():
    p, X, W, H, s = 7, 2.0, 2.0, 4.0, 0.75
    R = Rect(W, H, p, X, s)
    t = R.t
    eta = (p - 1) * sqrt((p - 2) / (12 * p))
    zeta = (5 * p + 2) / (p - 2)
    d0 = W / eta
    delta = H / X * sqrt(zeta**2 - 1)
    G0 = (W, H + H * zeta / X)
    Oarc = (W - d0 + delta, H - H / (X * eta))
    rad = G0[1] - R.E[1]
    foot = (W - d0, Oarc[1])
    D = (W - d0, Oarc[1] - sqrt(rad**2 - delta**2))
    # consistency with the scalar formula
    q5 = sqrt(((p - 2) * (t * t + 1) + (10 * p + 4) * t) / (12 * p))
    kap = (H - D[1]) / (W - D[0]) * W * X / H
    assert abs(kap - (1 + (p - 1) * q5)) < 1e-12
    T, Pp = R.step(R.A, (D[0] - W, D[1] - H))
    assert abs((1 - Pp[1] / H) - s * kap / (kap - 1 + t)) < 1e-12

    macro("figDecentered")
    emit(r"\begin{tikzpicture}[scale=0.25]")
    emit(r"\node[ttl] at (-3,23.6) {(a) Circle geometry};")
    emit(rf"\draw[line width=0.5pt,black!55] (0,0) rectangle ({W},{H});")
    emit(rf"\draw[accent] {c(Oarc)} circle ({rad:.4f});")
    emit(rf"\draw[aux] ({W - d0:.4f},-13.4)--({W - d0:.4f},9.0);")
    emit(rf"\draw[accent,line width=2.2pt] {c(R.E)}--{c(G0)};")
    emit(rf"\draw[line width=0.8pt] {c(D)}--{c(foot)}--{c(Oarc)};")
    emit(rf"\draw[line width=0.8pt,acc] {c(Oarc)}--{c(D)};")
    emit(rf"\draw[line width=0.5pt] ({foot[0]:.4f},{foot[1] - 0.8:.4f})-|({foot[0] + 0.8:.4f},{foot[1]:.4f});")
    for q in (G0, R.E, Oarc, D, foot):
        emit(rf"\node[pt] at {c(q)} {{}};")
    emit(rf"\node[lab,left] at {c(G0)} {{$G_0$}};")
    emit(rf"\node[lab,anchor=south west] at ({W + 0.15:.4f},{R.E[1] + 0.2:.4f}) {{$E$}};")
    emit(rf"\node[lab,above right] at {c(Oarc)} {{$O_{{\mathrm{{arc}}}}$}};")
    emit(rf"\node[lab,below left] at {c(D)} {{$D_{{\mathrm{{arc}}}}$}};")
    emit(rf"\node[lab,anchor=west,acc] at ({W + 0.9:.4f},20.6) {{compass opening $EG_0=\frac HX(t+\zeta)$}};")
    emit(rf"\node[lab,above] at ({(foot[0] + Oarc[0]) / 2:.4f},{Oarc[1]:.4f}) {{$\delta$}};")
    emit(rf"\node[lab,anchor=north west,acc] at ({(D[0] + Oarc[0]) / 2:.4f},{(D[1] + Oarc[1]) / 2 - 0.2:.4f}) {{radius $EG_0$}};")
    emit(rf"\node[lab,anchor=north west,align=left] at ({W - d0 + 2.6:.4f},-5.6) {{vertical $x=W-d_0$\\[3pt]$\bigl|y_{{D_{{\mathrm{{arc}}}}}}-y_{{O_{{\mathrm{{arc}}}}}}\bigr|=\sqrt{{EG_0^{{2}}-\delta^{{2}}}}$}};")
    emit(rf"\node[font=\footnotesize,black!60,anchor=east] at (-0.3,1.3) {{rectangle}};")

    # panel (b): 1 unit = 1.62 cm
    sc = 6.48
    emit(rf"\begin{{scope}}[shift={{(41.5,-5.0)}},scale={sc}]")
    emit(rf"\node[ttl] at (-0.45,{28.6 / sc:.4f}) {{(b) Support and readout}};")
    R.base()
    emit(rf"\draw[support] {c(R.A)}--{c(D)};")
    R.transport(T, Pp)
    R.corners(cl="left", bl="below right")
    R.points(T, Pp, tl="above left", pl="right", ppl="right")
    emit(rf"\node[pt] at {c(D)} {{}};")
    emit(rf"\node[lab,below] at {c(D)} {{$D_{{\mathrm{{arc}}}}$}};")
    emit(r"\end{scope}")
    emit(r"\end{tikzpicture}%")
    end()


