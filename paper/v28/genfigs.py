def fig_ad():
    R = cubic_rect()
    p, X, W, H = R.p, R.X, R.W, R.H
    Oad = (W - 2 * W / (p - 1), H - H * (p + 1) / (X * (p - 1)))
    AE = H * R.s**p
    D = (Oad[0], Oad[1] - AE)
    T, Pp = R.step(R.A, (D[0] - W, D[1] - H))
    kap = (p + 1 + (p - 1) * R.t) / 2
