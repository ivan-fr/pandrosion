    K = (R.W * (1 - R.X / R.p), 0)
    T, Pp = R.step(R.A, (K[0] - R.W, K[1] - R.H))
    assert abs((1 - Pp[1] / R.H) - R.p * R.s / (R.p - 1 + R.t)) < 1e-12
    macro("figAK")
    emit(r"\begin{tikzpicture}[scale=1.5]")
    R.base()
    emit(rf"\draw[support] {c(R.A)}--{c(K)};")
    R.transport(T, Pp)
    R.corners()
    R.points(T, Pp, tl=None)
    emit(rf"\node[pt] at {c(K)} {{}};")
