"""Generate figs.tex: all figures of the paper as TikZ, from exact coordinates.

Every point is computed from the formulas of the paper; nothing is traced
from an earlier drawing.  Run:  python3 genfigs.py > figs.tex
"""
from math import sqrt

OUT = []


def emit(s=""):
    OUT.append(s)


def c(pt):
    return f"({pt[0]:.4f},{pt[1]:.4f})"


def meet(p1, d1, p2, d2):
    """Intersection of p1 + a d1 and p2 + b d2."""
    det = d1[0] * (-d2[1]) - d1[1] * (-d2[0])
    rx, ry = p2[0] - p1[0], p2[1] - p1[1]
    a = (rx * (-d2[1]) - ry * (-d2[0])) / det
    return (p1[0] + a * d1[0], p1[1] + a * d1[1])


