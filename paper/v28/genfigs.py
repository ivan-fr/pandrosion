class Rect:
    """Pandrosion rectangle with the triangle power stage and transport."""

    def __init__(self, W, H, p, X, s):
        self.W, self.H, self.p, self.X, self.s = W, H, p, X, s
        self.t = X * s**p
        self.O, self.A, self.C, self.B = (0, H), (W, H), (0, 0), (W, 0)
        self.M = (0, H * (1 - 1 / X))
        self.E = (W, H * (1 - s**p))
        self.P = (W, H * (1 - s))
        self.sigma = (self.E[1] - self.M[1]) / W

    def base(self, chain=True):
        W, H, p, s = self.W, self.H, self.p, self.s
        if chain:
            emit(rf"\draw[chain] {c(self.O)}--{c(self.B)};")
            L1 = (0, H * (1 - s))
            emit(rf"\draw[chain] {c(L1)}--{c(self.B)};")
            for j in range(1, p + 1):
                y = H * (1 - s**j)
                emit(rf"\draw[chain] (0,{y:.4f})--({W},{y:.4f});")
            for j in range(1, p):
                Bj = (W * s**j, H * (1 - s**j))
                Lj1 = (0, H * (1 - s ** (j + 1)))
                emit(rf"\draw[chainpar] {c(Bj)}--{c(Lj1)};")
        emit(rf"\draw[rect] {c(self.C)} rectangle {c(self.A)};")

    def step(self, a0, d0):
        """Support through a0 with direction d0; returns T and P_+."""
        T = meet(a0, d0, self.P, (1, self.sigma))
        Pp = (self.W, T[1])
        return T, Pp

    def transport(self, T, Pp):
        emit(rf"\draw[transport] {c(self.M)}--{c(self.E)};")
        emit(rf"\draw[transport] {c(self.P)}--{c(T)};")
        emit(rf"\draw[transport,line width=1.5pt] {c(T)}--{c(Pp)};")

    def corners(self, cl="below left", bl="below right", al="above right"):
        emit(rf"\node[lab,above left] at {c(self.O)} {{$O$}};")
        emit(rf"\node[lab,{al}] at {c(self.A)} {{$A$}};")
        emit(rf"\node[lab,{cl}] at {c(self.C)} {{$C$}};")
        emit(rf"\node[lab,{bl}] at {c(self.B)} {{$B$}};")

    def points(self, T, Pp, tl="below left", pl="above right", ppl="below right"):
        for q in (self.O, self.A, self.C, self.B, self.M, self.E, self.P, T, Pp):
            emit(rf"\node[pt] at {c(q)} {{}};")
        emit(rf"\node[lab,left] at {c(self.M)} {{$M$}};")
        emit(rf"\node[lab,right] at {c(self.E)} {{$E$}};")
        emit(rf"\node[lab,{pl}] at {c(self.P)} {{$P$}};")
        emit(rf"\node[lab,{ppl}] at {c(Pp)} {{$P_+$}};")
        if tl:
            emit(rf"\node[lab,{tl}] at {c(T)} {{$T$}};")


def zoom(R, T, Pp, at, mag, extra=None, pad=0.14, pady=0.2):
    """Magnified inset of the window around P, T, P_+; `at` is its lower-left corner."""
    x0, x1 = T[0] - pad, R.W + 0.6 * pad
    y0, y1 = min(R.P[1], Pp[1]) - pady, max(R.P[1], Pp[1]) + pady
    emit(rf"\draw[aux] ({x0:.4f},{y0:.4f}) rectangle ({x1:.4f},{y1:.4f});")
    emit(rf"\node[lab,left] at ({x0:.4f},{T[1]:.4f}) {{$T$}};")
    sx, sy = at[0] - mag * x0, at[1] - mag * y0
    emit(rf"\begin{{scope}}[shift={{({sx:.4f},{sy:.4f})}},scale={mag}]")
    emit(rf"\begin{{scope}}")
    emit(rf"\clip ({x0:.4f},{y0:.4f}) rectangle ({x1:.4f},{y1:.4f});")
    emit(rf"\fill[white] ({x0:.4f},{y0:.4f}) rectangle ({x1:.4f},{y1:.4f});")
    emit(rf"\draw[rect] ({R.W},{y0 - 1:.4f})--({R.W},{y1 + 1:.4f});")
    if extra:
        extra()
    far = (R.P[0] - 5, R.P[1] - 5 * R.sigma)
    emit(rf"\draw[transport] {c(R.P)}--{c(far)};")
    emit(rf"\draw[transport,line width=1.6pt] {c(T)}--{c(Pp)};")
    for q in (R.P, T, Pp):
        emit(rf"\node[pt] at {c(q)} {{}};")
    emit(r"\end{scope}")
    emit(rf"\draw[line width=0.6pt] ({x0:.4f},{y0:.4f}) rectangle ({x1:.4f},{y1:.4f});")
    emit(rf"\node[lab,right] at ({x1:.4f},{R.P[1]:.4f}) {{$P$}};")
    emit(rf"\node[lab,right] at ({x1:.4f},{Pp[1]:.4f}) {{$P_+$}};")
    emit(rf"\node[lab,left] at ({x0:.4f},{T[1]:.4f}) {{$T$}};")
    emit(rf"\node[font=\footnotesize,anchor=south west] at ({x0:.4f},{y1:.4f}) {{Readout detail (magnified $\times{mag}$)}};")
    emit(r"\end{scope}")


def macro(name):
    emit(rf"\newcommand{{\{name}}}{{%")


def end():
    emit("}")
    emit()


